"""Add earlier years (2021-2024 by default) to the synthetic retail CSVs.

The source folder holds 2025 (flat, as delivered) and 2026 (generated by
``extend_sales_data.py``). This script appends several years of history
before them, without changing any existing row:

* FactSales.csv   sales lines for every day of each added year
* DimDate.csv     every date of each added year
* FactTarget.csv  monthly targets per store and category
* README.csv      period and row count

The history is generated with the same order-level rules as 2026 (every
line of an order shares date, store, customer, channel and payment
method; prices and costs from DimProduct) plus a story across the years:

* the business grows each year (``YEAR_SCALE``) and stores grow at
  different rates, so rankings change over time
* Ramadan and Eid al-Fitr on each year's own dates; Saudi National Day
  (23 Sep) and White Friday (late November) peaks with deeper discounts
* delivery, click-and-collect and wallet payments grow year by year
* seasonal category effects (summer beverages, Ramadan food, back-to-school
  accessories)

Usage (dry run prints a summary and writes nothing):

    python scripts/add_history_years.py
    python scripts/add_history_years.py --write
    python scripts/add_history_years.py --years 2022 2023 2024 --write

``--write`` first copies the folder to ``<folder>_backup_before_history``
and refuses to run if any of the years is already present. Output is
deterministic for a given ``--seed``. Afterwards refresh and publish the
dataset in Power BI Desktop.
"""

import argparse
import datetime as dt
import shutil
import sys
from pathlib import Path

import numpy as np
import pandas as pd

DEFAULT_DIR = Path(r"L:\Downloads\Saudi_Retail_MVP_PowerBI_Dataset")
DEFAULT_YEARS = [2021, 2022, 2023, 2024]

# Size of each year relative to 2025 (lines per day).
YEAR_SCALE = {2019: 0.42, 2020: 0.40, 2021: 0.55, 2022: 0.68, 2023: 0.80,
              2024: 0.92}
# Ramadan (first and last day) and Eid al-Fitr holidays, Saudi calendar.
RAMADAN = {
    2019: (dt.date(2019, 5, 6), dt.date(2019, 6, 3)),
    2020: (dt.date(2020, 4, 24), dt.date(2020, 5, 23)),
    2021: (dt.date(2021, 4, 13), dt.date(2021, 5, 12)),
    2022: (dt.date(2022, 4, 2), dt.date(2022, 5, 1)),
    2023: (dt.date(2023, 3, 23), dt.date(2023, 4, 20)),
    2024: (dt.date(2024, 3, 11), dt.date(2024, 4, 9)),
}
EID_DAYS = 4

WEEKDAY_FACTOR = {  # Monday = 0
    0: 0.90, 1: 0.90, 2: 0.96, 3: 1.10, 4: 1.26, 5: 1.20, 6: 0.97,
}
MONTH_FACTOR = {
    1: 0.96, 2: 0.98, 3: 1.02, 4: 0.98, 5: 1.00, 6: 1.06, 7: 1.10,
    8: 1.08, 9: 1.04, 10: 0.99, 11: 1.06, 12: 1.09,
}
LINES_PER_ORDER = ([1, 2, 3, 4, 5, 6], [0.44, 0.30, 0.15, 0.07, 0.03, 0.01])
DISCOUNT_RATES = [0.0, 0.03, 0.05, 0.10, 0.15]
DISCOUNT_NORMAL = [0.475, 0.12, 0.20, 0.155, 0.05]
DISCOUNT_PROMO = [0.30, 0.10, 0.22, 0.24, 0.14]
# Channel and payment trends: 0 = 2021 levels, 1 = 2025 levels.
TREND = {2019: -0.3, 2020: -0.1, 2021: 0.0, 2022: 0.25, 2023: 0.5, 2024: 0.75}


class Calendar:
    """Special days of one year."""

    def __init__(self, year):
        self.year = year
        self.ramadan = RAMADAN[year]
        start = self.ramadan[1] + dt.timedelta(days=1)
        self.eid = (start, start + dt.timedelta(days=EID_DAYS - 1))
        self.national_day = dt.date(year, 9, 23)
        # White Friday: the last Friday of November and the two days after.
        last = dt.date(year, 11, 30)
        friday = last - dt.timedelta(days=(last.weekday() - 4) % 7)
        self.white_friday = (friday, friday + dt.timedelta(days=2))

    @staticmethod
    def within(day, span):
        return span[0] <= day <= span[1]

    def day_factor(self, day):
        factor = MONTH_FACTOR[day.month] * WEEKDAY_FACTOR[day.weekday()]
        if self.within(day, self.ramadan):
            factor *= 1.15
        if self.within(day, self.eid):
            factor *= 1.35
        if abs((day - self.national_day).days) <= 1:
            factor *= 1.25
        if self.within(day, self.white_friday):
            factor *= 1.45
        return factor

    def category_factor(self, category, day):
        if category == "Beverages" and day.month in (6, 7, 8):
            return 1.30
        if category == "Food" and self.within(day, self.ramadan):
            return 1.40
        if category == "Snacks" and self.within(day, self.eid):
            return 1.35
        if category == "Accessories" and (day.month == 9
                                          or self.within(day, self.white_friday)):
            return 1.45
        return 1.0

    def is_promo(self, day):
        next_month = (day.replace(day=28) + dt.timedelta(days=4)).replace(day=1)
        month_end = (next_month - day).days <= 3
        return (month_end or self.within(day, self.ramadan)
                or self.within(day, self.eid)
                or self.within(day, self.white_friday)
                or abs((day - self.national_day).days) <= 1)


def channel_weights(trend):
    delivery = 0.14 + 0.11 * trend
    collect = 0.03 + 0.04 * trend
    return ["In-Store", "Delivery", "Click & Collect"], [
        1 - delivery - collect, delivery, collect]


def payment_weights(channel, trend):
    names = ["Card", "Cash", "Online", "Wallet"]
    if channel == "In-Store":
        cash = 0.42 - 0.12 * trend
        wallet = 0.03 + 0.09 * trend
        return names, [1 - cash - wallet, cash, 0.0, wallet]
    online = 0.50 - 0.07 * trend
    wallet = 0.08 + 0.12 * trend
    return names, [1 - online - wallet - 0.06, 0.06, online, wallet]


def build_dates(years):
    rows = []
    for year in years:
        day = dt.date(year, 1, 1)
        while day.year == year:
            rows.append({
                "DateKey": int(day.strftime("%Y%m%d")),
                "Date": day.isoformat(),
                "Year": day.year,
                "Quarter": f"Q{(day.month - 1) // 3 + 1}",
                "MonthNumber": day.month,
                "MonthName": day.strftime("%B"),
                "YearMonth": day.strftime("%Y-%m"),
                "WeekNumber": day.isocalendar()[1],
                "DayName": day.strftime("%A"),
                "IsWeekend": day.weekday() in (4, 5, 6),
            })
            day += dt.timedelta(days=1)
    return pd.DataFrame(rows)


def build_targets(targets, years, store_level, rng):
    base = targets[targets.YearMonth.str.startswith("2025-")].copy()
    frames = []
    for year in years:
        frame = base.copy()
        frame["YearMonth"] = frame.YearMonth.str.replace("2025-", f"{year}-", regex=False)
        frame["SalesTargetSAR"] = [
            round(value * YEAR_SCALE[year] * store_level[year][store]
                  * rng.uniform(0.97, 1.05), 2)
            for value, store in zip(frame.SalesTargetSAR, frame.StoreKey)]
        frames.append(frame)
    return pd.concat(frames, ignore_index=True)


def store_levels(store_keys, years, rng):
    """Each store's size relative to its 2025 share, per year. Stores that
    grew fast by 2025 were smaller earlier, and the reverse."""

    growth = rng.uniform(-0.12, 0.12, size=len(store_keys))  # per year
    levels = {}
    for year in years:
        steps = 2025 - year
        levels[year] = {int(key): float(max(0.35, 1 - g * steps))
                        for key, g in zip(store_keys, growth)}
    return levels


def build_sales(sales, products, stores, customers, years, store_level, rng):
    base_lines_per_day = len(sales[sales.DateKey // 10000 == 2025]) / 365
    mean_lines = float(np.dot(*LINES_PER_ORDER))

    store_share = sales.StoreKey.value_counts(normalize=True).sort_index()
    store_keys = store_share.index.to_numpy()
    store_city = stores.set_index("StoreKey").City.to_dict()

    product_share = sales.ProductKey.value_counts(normalize=True)
    products = products.set_index("ProductKey")
    product_keys = products.index.to_numpy()
    product_base = np.array([product_share.get(key, 0.002) for key in product_keys])
    product_category = products.Category.to_numpy()

    customer_keys = customers.CustomerKey.to_numpy()
    loyalty = rng.lognormal(mean=0.0, sigma=0.9, size=len(customer_keys))
    by_city = {
        city: np.flatnonzero(customers.City.to_numpy() == city)
        for city in customers.City.unique()}
    all_customer_weights = loyalty / loyalty.sum()

    quantity_column = "Quantity" if "Quantity" in sales.columns else "TotalQuantity"
    quantity_values = sales[quantity_column].value_counts(normalize=True).sort_index()

    line_id = int(sales.SalesLineID.max())
    order_number = int(sales.OrderID.str[4:].astype(int).max())
    rows = []

    for year in years:
        calendar = Calendar(year)
        trend = TREND[year]
        level = store_level[year]
        store_weights = store_share.to_numpy() * np.array(
            [level[int(key)] for key in store_keys])
        store_weights = store_weights / store_weights.sum()
        channels, channel_p = channel_weights(trend)
        # Peaks move sales between days; the year's total follows YEAR_SCALE.
        all_days = [dt.date(year, 1, 1) + dt.timedelta(days=i)
                    for i in range((dt.date(year, 12, 31) - dt.date(year, 1, 1)).days + 1)]
        mean_factor = float(np.mean([calendar.day_factor(d) for d in all_days]))
        day = dt.date(year, 1, 1)
        while day.year == year:
            expected = (base_lines_per_day * YEAR_SCALE[year]
                        * calendar.day_factor(day) / mean_factor / mean_lines)
            order_count = rng.poisson(expected * rng.lognormal(0.0, 0.07))
            product_weights = product_base * np.array(
                [calendar.category_factor(c, day) for c in product_category])
            product_weights = product_weights / product_weights.sum()
            discounts = DISCOUNT_PROMO if calendar.is_promo(day) else DISCOUNT_NORMAL
            date_key = int(day.strftime("%Y%m%d"))

            for _ in range(order_count):
                order_number += 1
                store = int(rng.choice(store_keys, p=store_weights))
                local = by_city.get(store_city[store])
                if local is not None and len(local) and rng.random() < 0.72:
                    weights = loyalty[local] / loyalty[local].sum()
                    customer = int(customer_keys[rng.choice(local, p=weights)])
                else:
                    customer = int(rng.choice(customer_keys, p=all_customer_weights))
                channel = str(rng.choice(channels, p=channel_p))
                payments, payment_p = payment_weights(channel, trend)
                payment = str(rng.choice(payments, p=payment_p))
                line_count = int(rng.choice(LINES_PER_ORDER[0], p=LINES_PER_ORDER[1]))
                chosen = rng.choice(product_keys, size=line_count, replace=False,
                                    p=product_weights)
                for product in chosen:
                    line_id += 1
                    quantity = int(rng.choice(quantity_values.index.to_numpy(),
                                              p=quantity_values.to_numpy()))
                    price = float(products.UnitPriceSAR[product])
                    unit_cost = float(products.UnitCostSAR[product])
                    gross = round(quantity * price, 2)
                    discount = round(gross * float(rng.choice(DISCOUNT_RATES, p=discounts)), 2)
                    net = round(gross - discount, 2)
                    cost = round(quantity * unit_cost, 2)
                    rows.append({
                        "SalesLineID": line_id,
                        "OrderID": f"ORD-{order_number:07d}",
                        "DateKey": date_key,
                        "StoreKey": store,
                        "ProductKey": int(product),
                        "CustomerKey": customer,
                        quantity_column: quantity,
                        "UnitPriceSAR": price,
                        "GrossSalesSAR": gross,
                        "DiscountSAR": discount,
                        "NetSalesSAR": net,
                        "CostSAR": cost,
                        "GrossProfitSAR": round(net - cost, 2),
                        "Channel": channel,
                        "PaymentMethod": payment,
                    })
            day += dt.timedelta(days=1)
    return pd.DataFrame(rows, columns=list(sales.columns))


def append_csv(path, frame):
    """Append rows in the file's own format (LF line endings, no index)."""

    text = frame.to_csv(index=False, header=False, lineterminator="\n")
    existing = path.read_bytes()
    with path.open("ab") as handle:
        if existing and not existing.endswith(b"\n"):
            handle.write(b"\n")
        handle.write(text.encode("utf-8"))


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--data-dir", type=Path, default=DEFAULT_DIR)
    parser.add_argument("--years", type=int, nargs="+", default=DEFAULT_YEARS)
    parser.add_argument("--seed", type=int, default=2021)
    parser.add_argument("--write", action="store_true",
                        help="back up the folder and append the new rows")
    args = parser.parse_args()

    years = sorted(set(args.years))
    unknown = [y for y in years if y not in YEAR_SCALE]
    if unknown:
        sys.exit(f"No settings for {unknown}; supported: {sorted(YEAR_SCALE)}.")

    folder = args.data_dir
    sales = pd.read_csv(folder / "FactSales.csv")
    dates = pd.read_csv(folder / "DimDate.csv")
    targets = pd.read_csv(folder / "FactTarget.csv")
    products = pd.read_csv(folder / "DimProduct.csv")
    stores = pd.read_csv(folder / "DimStore.csv")
    customers = pd.read_csv(folder / "DimCustomer.csv")

    present = sorted(set(years) & (set(dates.Year) | set(sales.DateKey // 10000)
                                   | set(targets.YearMonth.str[:4].astype(int))))
    if present:
        sys.exit(f"{folder} already contains {present}; nothing was changed.")

    rng = np.random.default_rng(args.seed)
    store_level = store_levels(sorted(stores.StoreKey), years, rng)
    new_dates = build_dates(years)
    new_targets = build_targets(targets, years, store_level, rng)
    new_sales = build_sales(sales, products, stores, customers, years,
                            store_level, rng)

    # Integrity checks before anything is written.
    quantity_column = "Quantity" if "Quantity" in sales.columns else "TotalQuantity"
    assert new_sales.SalesLineID.is_unique
    assert not set(new_sales.SalesLineID) & set(sales.SalesLineID)
    assert not set(new_sales.OrderID) & set(sales.OrderID)
    assert set(new_sales.DateKey) <= set(new_dates.DateKey)
    assert not set(new_dates.DateKey) & set(dates.DateKey)
    assert set(new_sales.StoreKey) <= set(stores.StoreKey)
    assert set(new_sales.ProductKey) <= set(products.ProductKey)
    assert set(new_sales.CustomerKey) <= set(customers.CustomerKey)
    assert set(new_sales.Channel) <= set(sales.Channel)
    assert set(new_sales.PaymentMethod) <= set(sales.PaymentMethod)
    assert (new_sales[quantity_column] > 0).all()
    assert np.allclose(new_sales.NetSalesSAR,
                       new_sales.GrossSalesSAR - new_sales.DiscountSAR)
    assert np.allclose(new_sales.GrossProfitSAR,
                       new_sales.NetSalesSAR - new_sales.CostSAR, atol=0.011)
    per_order = new_sales.groupby("OrderID")[
        ["DateKey", "StoreKey", "CustomerKey", "Channel", "PaymentMethod"]].nunique()
    assert (per_order == 1).all().all()
    assert len(new_targets) == 12 * 80 * len(years)

    yearly = new_sales.assign(Year=new_sales.DateKey // 10000).groupby("Year").agg(
        Lines=("SalesLineID", "size"), Orders=("OrderID", "nunique"),
        NetSales=("NetSalesSAR", "sum")).round(0)
    existing = sales.assign(Year=sales.DateKey // 10000).groupby("Year").agg(
        Lines=("SalesLineID", "size"), Orders=("OrderID", "nunique"),
        NetSales=("NetSalesSAR", "sum")).round(0)
    print(f"Folder: {folder}")
    print("New years:\n" + yearly.to_string())
    print("Existing years:\n" + existing.to_string())
    print(f"New sales lines: {len(new_sales):,}; new dates: {len(new_dates):,}; "
          f"new target rows: {len(new_targets):,}")
    print(f"FactSales after: {len(sales) + len(new_sales):,} rows")

    if not args.write:
        print("\nDry run: nothing was written. Add --write to apply.")
        return

    backup = folder.with_name(folder.name + "_backup_before_history")
    if backup.exists():
        sys.exit(f"Backup folder already exists: {backup}. Nothing was changed.")
    shutil.copytree(folder, backup)
    print(f"\nBackup of the current files: {backup}")

    append_csv(folder / "FactSales.csv", new_sales)
    append_csv(folder / "DimDate.csv", new_dates)
    append_csv(folder / "FactTarget.csv", new_targets)

    readme = folder / "README.csv"
    lines = readme.read_text(encoding="utf-8").splitlines()
    first = min(years)
    total = len(sales) + len(new_sales)
    for index, line in enumerate(lines):
        if line.startswith("Period,"):
            lines[index] = (
                f"Period,1 Jan {first} to 16 Nov 2026 ({first}-{max(years)} added "
                "by InsightPilot scripts/add_history_years.py; 2026 by "
                "scripts/extend_sales_data.py)")
        elif line.startswith("FactSales grain,"):
            lines[index] = f'FactSales grain,"One row per sales line; {total:,} rows"'
    readme.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Written. FactSales now has {total:,} rows.")


if __name__ == "__main__":
    main()
