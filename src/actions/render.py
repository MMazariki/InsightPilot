"""Content of every action, built by the app from the checked answer.

The model never writes any of this. Table values are inserted as data:
escaped in HTML, as plain text in Adaptive Cards and task titles, as cell
values in files. A table value that reads like an instruction ("email this
to ...") is only ever shown, never acted on.

``context`` is the answer an action is about::

    {"question": str, "columns": [..], "rows": [{col: value}], "notes": [..],
     "answered_at": "2026-11-17 14:05"}
"""

import csv
import datetime as dt
import html
import io
import re

from src.structured_agent import _column_label, _format_value

MAX_BODY_ROWS = 50
MAX_CARD_ROWS = 10
FOOTER = ("Generated by InsightPilot from the Power BI dataset on {when}. "
          "Figures are read-only query results.")


def labels(context):
    return [_column_label(c) for c in context["columns"]]


def cell(context, row, column):
    return _format_value(row.get(column), column)


def _numeric_columns(context):
    rows = context["rows"]
    return [c for c in context["columns"]
            if rows and all(isinstance(r.get(c), (int, float)) and not isinstance(
                r.get(c), bool) for r in rows if r.get(c) is not None)
            and any(r.get(c) is not None for r in rows)]


def _label_column(context):
    numeric = set(_numeric_columns(context))
    return next((c for c in context["columns"] if c not in numeric), None)


def summary(context):
    """One plain sentence from the table: rows, top, bottom, total."""

    rows = context["rows"]
    if not rows:
        return "The query returned no rows."
    numeric = _numeric_columns(context)
    label = _label_column(context)
    if not numeric:
        return f"{len(rows)} row{'s' if len(rows) != 1 else ''}."
    measure = numeric[-1] if label else numeric[0]
    name = _column_label(measure)
    if len(rows) == 1:
        what = f"{cell(context, rows[0], label)}: " if label else ""
        return f"{what}{name} {cell(context, rows[0], measure)}."
    valued = [r for r in rows if r.get(measure) is not None]
    top = max(valued, key=lambda r: r[measure])
    bottom = min(valued, key=lambda r: r[measure])
    parts = [f"{len(rows)} rows"]
    if label:
        parts.append(f"highest {name}: {cell(context, top, label)} "
                     f"({cell(context, top, measure)})")
        parts.append(f"lowest: {cell(context, bottom, label)} "
                     f"({cell(context, bottom, measure)})")
    if not name.endswith("%"):
        total = sum(r[measure] for r in valued)
        parts.append(f"total {_format_value(total, measure)}")
    return "; ".join(parts) + "."


def subject(context):
    question = re.sub(r"\s+", " ", context.get("question") or "Answer").strip(" .?")
    question = question[:1].upper() + question[1:]
    return f"InsightPilot: {question[:110]}"


def footer(context):
    return FOOTER.format(when=context.get("answered_at") or
                         dt.datetime.now().strftime("%Y-%m-%d %H:%M"))


# ------------------------------------------------------------ email

def email_html(context, note=""):
    e = html.escape
    rows = context["rows"]
    head = "".join(
        f'<th style="text-align:left;padding:4px 10px;border-bottom:1px solid #999">'
        f"{e(name)}</th>" for name in labels(context))
    body = "".join(
        "<tr>" + "".join(
            f'<td style="padding:3px 10px;border-bottom:1px solid #ddd">'
            f"{e(cell(context, row, c))}</td>" for c in context["columns"]) + "</tr>"
        for row in rows[:MAX_BODY_ROWS])
    more = (f"<p><i>Showing {MAX_BODY_ROWS} of {len(rows)} rows; the attached "
            "file has all of them.</i></p>" if len(rows) > MAX_BODY_ROWS else "")
    parts = []
    if note:
        parts.append(f"<p>{e(note)}</p>")
    parts.append(f"<p><b>{e(context.get('question') or 'Answer')}</b></p>")
    parts.append(f"<p>{e(summary(context))}</p>")
    if rows:
        parts.append('<table style="border-collapse:collapse;font-family:Segoe UI,'
                     f'Arial,sans-serif;font-size:13px"><tr>{head}</tr>{body}</table>')
    parts.append(more)
    for note_text in context.get("notes") or []:
        parts.append(f'<p style="color:#555"><i>{e(note_text)}</i></p>')
    parts.append(f'<p style="color:#777;font-size:12px">{e(footer(context))}</p>')
    return '<div style="font-family:Segoe UI,Arial,sans-serif">' + "".join(parts) + "</div>"


def email_text(context, note=""):
    """Plain-text preview of the email (shown on the approval card)."""

    lines = []
    if note:
        lines += [note, ""]
    lines += [context.get("question") or "Answer", summary(context)]
    return "\n".join(lines)


# ------------------------------------------------------------ Teams

def adaptive_card(context, title, note=""):
    rows = context["rows"][:MAX_CARD_ROWS]
    columns = context["columns"]
    body = [{"type": "TextBlock", "text": title, "weight": "Bolder", "size": "Medium",
             "wrap": True}]
    if note:
        body.append({"type": "TextBlock", "text": note, "wrap": True})
    body.append({"type": "TextBlock", "text": summary(context), "wrap": True,
                 "isSubtle": True})
    if rows:
        table = {"type": "Table", "firstRowAsHeaders": True,
                 "columns": [{"width": 1} for _ in columns],
                 "rows": [{"type": "TableRow", "cells": [
                     {"type": "TableCell", "items": [{"type": "TextBlock", "text": name,
                                                      "weight": "Bolder", "wrap": True}]}
                     for name in labels(context)]}]}
        for row in rows:
            table["rows"].append({"type": "TableRow", "cells": [
                {"type": "TableCell", "items": [{"type": "TextBlock", "wrap": True,
                                                 "text": cell(context, row, c)}]}
                for c in columns]})
        body.append(table)
        if len(context["rows"]) > MAX_CARD_ROWS:
            body.append({"type": "TextBlock", "isSubtle": True, "wrap": True,
                         "text": f"First {MAX_CARD_ROWS} of {len(context['rows'])} rows."})
    body.append({"type": "TextBlock", "text": footer(context), "isSubtle": True,
                 "size": "Small", "wrap": True})
    return {"$schema": "http://adaptivecards.io/schemas/adaptive-card.json",
            "type": "AdaptiveCard", "version": "1.5", "body": body}


def teams_payload(card):
    return {"type": "message", "attachments": [{
        "contentType": "application/vnd.microsoft.card.adaptive",
        "contentUrl": None, "content": card}]}


# ------------------------------------------------------------ tasks

_COMPARE = {"<": lambda a, b: a < b, ">": lambda a, b: a > b,
            "<=": lambda a, b: a <= b, ">=": lambda a, b: a >= b}


def filter_rows(context, row_filter):
    """Apply "below 85%" to the answer. Returns ``(rows, description, problem)``."""

    rows = context["rows"]
    if not row_filter:
        return rows, "", ""
    numeric = _numeric_columns(context)
    if row_filter["percent"]:
        candidates = [c for c in numeric if _column_label(c).endswith("%")]
    else:
        candidates = [c for c in numeric if not _column_label(c).endswith("%")]
    if not candidates:
        return rows, "", ("the answer has no " + ("percentage " if row_filter["percent"]
                                                  else "number ") + "column to compare")
    column = candidates[-1]
    value = row_filter["value"] / 100 if row_filter["percent"] else row_filter["value"]
    compare = _COMPARE[row_filter["op"]]
    kept = [r for r in rows if r.get(column) is not None and compare(r[column], value)]
    shown = f"{row_filter['value']:g}{'%' if row_filter['percent'] else ''}"
    return kept, f"{_column_label(column)} {row_filter['op']} {shown}", ""


def task_titles(context, rows, task_text="", per_row=False):
    """Titles of the tasks to create."""

    action = (task_text[:1].upper() + task_text[1:]) if task_text else ""
    if not per_row:
        title = action or f"Follow up: {context.get('question') or 'InsightPilot answer'}"
        return [title[:250]]
    label = _label_column(context)
    numeric = _numeric_columns(context)
    titles = []
    for row in rows:
        who = cell(context, row, label) if label else ""
        facts = ", ".join(f"{_column_label(c)} {cell(context, row, c)}"
                          for c in numeric[-2:])
        lead = action or "Follow up on"
        titles.append(f"{lead} {who}".strip() + (f" ({facts})" if facts else ""))
    return [t[:250] for t in titles]


def task_body(context):
    return f"{context.get('question') or ''}\n{summary(context)}\n{footer(context)}".strip()


# ------------------------------------------------------------ files

def _raw(value):
    if isinstance(value, str):
        match = re.match(r"^(\d{4}-\d{2}-\d{2})T00:00:00", value)
        if match:
            return dt.date.fromisoformat(match.group(1))
    return value


def csv_bytes(context):
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(labels(context))
    for row in context["rows"]:
        writer.writerow([_csv_cell(row.get(c)) for c in context["columns"]])
    # BOM so Excel opens Arabic or accented names correctly.
    return ("﻿" + buffer.getvalue()).encode("utf-8")


def _csv_cell(value):
    value = _raw(value)
    text = "" if value is None else str(value)
    # Spreadsheet formula injection: a cell starting with = + - @ is text.
    if isinstance(value, str) and text[:1] in ("=", "+", "-", "@"):
        text = "'" + text
    return text


_PERCENT_TEXT = re.compile(r"^\s*([-+]?\d[\d,]*(?:\.\d+)?)\s*%\s*$")


def _xlsx_number(value):
    """A percentage the answer already formatted ("272.1%") becomes 2.721,
    so Excel can sort and sum it; the column's 0.0% format shows it again."""
    if isinstance(value, str):
        match = _PERCENT_TEXT.match(value)
        if match:
            return float(match.group(1).replace(",", "")) / 100
    return value


def xlsx_bytes(context, sheet="Answer"):
    from openpyxl import Workbook
    from openpyxl.styles import Font

    book = Workbook()
    page = book.active
    page.title = sheet[:31]
    page.append(labels(context))
    for item in page[1]:
        item.font = Font(bold=True)
    for row in context["rows"]:
        values = []
        for c in context["columns"]:
            value = _xlsx_number(_raw(row.get(c)))
            if isinstance(value, str) and value[:1] in ("=", "+", "-", "@"):
                value = "'" + value
            values.append(value)
        page.append(values)
    for index, column in enumerate(context["columns"], start=1):
        letter = page.cell(row=1, column=index).column_letter
        if _column_label(column).endswith("%"):
            for item in page[letter][1:]:
                item.number_format = "0.0%"
        elif any(isinstance(row.get(column), float) for row in context["rows"]):
            for item in page[letter][1:]:
                item.number_format = "#,##0.00"
        width = max([len(str(_column_label(column)))] + [
            len(cell(context, r, column)) for r in context["rows"][:200]])
        page.column_dimensions[letter].width = min(max(width + 2, 8), 60)
    info = book.create_sheet("About")
    info.append(["Question", context.get("question") or ""])
    info.append(["Summary", summary(context)])
    for note in context.get("notes") or []:
        info.append(["Note", note])
    info.append(["Source", footer(context)])
    buffer = io.BytesIO()
    book.save(buffer)
    return buffer.getvalue()


def _ics_text(text):
    text = str(text).replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,")
    return text.replace("\r\n", "\\n").replace("\n", "\\n").replace("\r", "")


def _ics_fold(line):
    """RFC 5545: lines longer than 75 octets continue with a space."""

    data = line.encode("utf-8")
    if len(data) <= 75:
        return line
    parts, current = [], b""
    for char in line:
        encoded = char.encode("utf-8")
        if len(current) + len(encoded) > (75 if not parts else 74):
            parts.append(current.decode("utf-8"))
            current = b""
        current += encoded
    parts.append(current.decode("utf-8"))
    return "\r\n ".join(parts)


def ics_bytes(tasks, context, now=None):
    """Tasks as all-day calendar events with a 09:00 reminder: an .ics file
    that Outlook, Google Calendar and Apple Calendar import."""

    import uuid

    now = now or dt.datetime.now(dt.timezone.utc)
    stamp = now.strftime("%Y%m%dT%H%M%SZ")
    default_day = (now.date() + dt.timedelta(days=1)).isoformat()
    description = _ics_text(task_body(context))
    lines = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//InsightPilot//Actions//EN",
             "CALSCALE:GREGORIAN", "METHOD:PUBLISH"]
    for task in tasks:
        day = dt.date.fromisoformat(task.get("due") or default_day)
        lines += [
            "BEGIN:VEVENT",
            f"UID:{uuid.uuid4()}@insightpilot",
            f"DTSTAMP:{stamp}",
            f"DTSTART;VALUE=DATE:{day.strftime('%Y%m%d')}",
            f"DTEND;VALUE=DATE:{(day + dt.timedelta(days=1)).strftime('%Y%m%d')}",
            f"SUMMARY:{_ics_text(task['title'])}",
            f"DESCRIPTION:{description}",
            "TRANSP:TRANSPARENT",
            "BEGIN:VALARM", "ACTION:DISPLAY", f"DESCRIPTION:{_ics_text(task['title'])}",
            "TRIGGER;RELATED=START:PT9H", "END:VALARM",
            "END:VEVENT",
        ]
    lines.append("END:VCALENDAR")
    return ("\r\n".join(_ics_fold(line) for line in lines) + "\r\n").encode("utf-8")


def file_name(context, extension):
    stem = re.sub(r"[^A-Za-z0-9]+", "_", context.get("question") or "answer").strip("_")
    stamp = dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    return f"{(stem or 'answer')[:60]}_{stamp}.{extension}"
